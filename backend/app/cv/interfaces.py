"""Replaceable CV and sensor boundaries; no model work belongs in the UI."""
from typing import Protocol
import numpy as np
class Detector(Protocol):
    def detect(self, image: np.ndarray) -> list[dict]: ...
class Tracker(Protocol):
    def update(self, detections: list[dict], timestamp: float, detected: bool=True) -> list[dict]: ...
class DepthEstimator(Protocol):
    def estimate(self, track: dict, width: int) -> dict | None: ...
class Segmenter(Protocol):
    def segment(self, image: np.ndarray) -> np.ndarray | None: ...
class PoseEstimator(Protocol):
    def pose(self, timestamp: float) -> dict | None: ...
class SceneAnalyzer(Protocol):
    def analyze(self, image: np.ndarray, count: int) -> dict: ...
class EnvironmentAdapter(Protocol):
    def read(self, timestamp: float) -> dict: ...
