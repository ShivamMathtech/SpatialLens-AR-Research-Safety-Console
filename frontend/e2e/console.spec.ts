import {test,expect} from '@playwright/test';
test('connected demo, controls, map, 3D, settings, replay and responsive layout',async({page,request})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.getByLabel('Username',{exact:true}).fill('browser_test');
 await page.getByLabel('Password',{exact:true}).fill('browser-test-only-password-123');
 await page.getByRole('button',{name:/Create account & enter|Open console/}).click();
 await expect(page.locator('nav')).toBeVisible();
 await page.getByRole('button',{name:'Start',exact:true}).click();
 await expect(page.locator('tbody tr')).toHaveCount(4,{timeout:15000});
 await page.waitForTimeout(500);
 await page.screenshot({path:'../docs/console-preview.png',fullPage:true});
 await page.getByTitle('Pause',{exact:true}).click();
 await expect(page.getByTitle('Resume',{exact:true})).toBeEnabled();
 await page.getByTitle('Resume',{exact:true}).click();
 await page.locator('tbody tr').first().click();
 await expect(page.getByText('SELECTED TRACK',{exact:false})).toBeVisible();
 await page.locator('nav').getByRole('button',{name:'Local map',exact:true}).click();
 await page.getByRole('button',{name:'topographic',exact:true}).click();
 await page.getByRole('button',{name:'Add waypoint',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Waypoint added');
 await page.locator('nav').getByRole('button',{name:'3D scene',exact:true}).click();
 await expect(page.locator('.webgl canvas')).toBeVisible();
 await page.getByRole('button',{name:'top',exact:true}).click();
 await page.locator('nav').getByRole('button',{name:'Research',exact:true}).click();
 await expect(page.getByText('Measured performance',{exact:true})).toBeVisible();
 await page.locator('nav').getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByLabel('Processing FPS target').fill('10');
 await page.getByRole('button',{name:'Save settings',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Settings saved');
 await page.getByTitle('Stop source').click();
 await page.locator('nav').getByRole('button',{name:'Replay',exact:true}).click();
 const selector=page.getByLabel('Recorded session');
 await expect(selector.locator('option')).not.toHaveCount(1);
 await selector.selectOption({index:1});
 await expect(page.getByTitle('Play replay',{exact:true})).toBeEnabled();
 await page.getByTitle('Next frame',{exact:true}).click();
 await page.getByTitle('Play replay',{exact:true}).click();
 await expect(page.getByTitle('Pause replay',{exact:true})).toBeVisible();
 await page.getByTitle('Pause replay',{exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.locator('nav').getByRole('button',{name:'Console',exact:true}).click();
 const size=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,window:window.innerWidth}));
 expect(size.scroll).toBeLessThanOrEqual(size.window+1);
 if(await page.getByRole('status').isVisible())await page.getByRole('status').click();
 await page.screenshot({path:'../docs/mobile-preview.png',fullPage:true});
 expect(errors).toEqual([]);
});
